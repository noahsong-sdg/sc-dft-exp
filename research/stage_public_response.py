"""Stage the documented full-symmetry geometry diagnostic from checked inputs."""
import argparse
import json
from pathlib import Path
import shutil

from fetch_public_response_inputs import digest, validate

RESEARCH = Path(__file__).resolve().parent


def stage(build, inputs, destination, manifest_path=RESEARCH/'public_response_inputs.json'):
    build, inputs, root = [Path(p).absolute() for p in (build, inputs, destination)]
    manifest = json.loads(Path(manifest_path).read_text())
    source = json.loads((build/'build-result.json').read_text())
    exe = Path(source['executable'])
    if exe != build/'probe/velocity-moment-probe.x' or digest(exe) != source['executable_sha256']:
        raise ValueError('Changed declared fresh-build executable')
    files = []
    for name, item in manifest['files'].items():
        path = inputs/validate(name, item)
        if path.stat().st_size != item['bytes'] or digest(path) != item['sha256']:
            raise ValueError('Changed declared public input: '+name)
        files.append(dict(path=str(path), bytes=item['bytes'], sha256=item['sha256']))
    template = (RESEARCH/'public_response_native.in.template').read_text()
    if template.count('@PUBLIC_INPUT_DIRECTORY@') != 1:
        raise ValueError('Changed public input template placeholder')
    native = template.replace('@PUBLIC_INPUT_DIRECTORY@', str(inputs).replace("'", "''"))
    root.mkdir(parents=True)  # All inputs must pass before a run directory exists.
    target = root/exe.name
    shutil.copy2(exe, target)
    (root/'native.in').write_text(native)
    for path in (target, root/'native.in', build/'build-result.json', Path(manifest_path),
                 RESEARCH/'public_response_native.in.template'):
        files.append(dict(path=str(path), bytes=path.stat().st_size, sha256=digest(path)))
    result = dict(files=files, command=[str(target), '-in', str(root/'native.in')], cwd=str(root),
                  environment=dict(OMP_NUM_THREADS='1', OPENBLAS_NUM_THREADS='1', SCTK_MOMENT_GRID='8'),
                  scope='Full48 tiny-Q selector diagnostic, not a production small-Q prediction; no gap solve',
                  matdyn0='Generated by QE q_points; not an acquired input')
    (root/'run-manifest.json').write_text(json.dumps(result, indent=2)+'\n')
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('build', 'inputs', 'destination'):
        parser.add_argument(name, type=Path)
    args = parser.parse_args()
    print(json.dumps(stage(args.build, args.inputs, args.destination), indent=2))
